// Builds the footer wordmark from Geist Pixel's own glyphs, so the pixel type is one family:
//
//   node scripts/wordmark-from-geist-pixel.mjs   (needs fonteditor-core: npm i)
//
// Geist Pixel draws every glyph as separate square cells on a 38-unit grid. This reads the cells of
// "Durable Runner" from the shipped public/fonts/geist-pixel-latin.woff2, lays the letters out by their
// own advances and writes src/components/ui/wordmark-cells.ts: one SVG path of separate squares (y down
// from the cap top), with the hairline gaps between cells drawn in, plus the size of the grid. Re-run it
// after changing the font file, and commit the output.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { cellsFor } from './lib/geist-cells.mjs'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const WORD = 'Durable Runner'

const { cells, cols, rows, capRows } = await cellsFor(WORD)

// Each cell is its own square, 9 units on a 10-unit grid: the hairline between cells is in the geometry, so the
// wordmark needs no mask (a mask over a large element is expensive to paint). After the first square every move
// is relative to the last, which keeps the path short and compresses well.
const UNIT = 10
const SIZE = 9
const parts = []
let prev = null
for (const { col, row } of [...cells].sort((a, b) => a.row - b.row || a.col - b.col)) {
  const x = col * UNIT
  const y = row * UNIT
  if (prev === null) parts.push(`M${x} ${y}h${SIZE}v${SIZE}h-${SIZE}z`)
  else parts.push(`m${x - prev[0]} ${y - prev[1]}h${SIZE}v${SIZE}h-${SIZE}z`)
  prev = [x, y]
}

const out = join(ROOT, 'src/components/ui/wordmark-cells.ts')
writeFileSync(
  out,
  '// Generated by scripts/wordmark-from-geist-pixel.mjs from public/fonts/geist-pixel-latin.woff2. Do not edit.\n' +
    `// "${WORD}" in Geist Pixel: ${cells.length} cells on a ${cols} x ${rows} grid, each a ${SIZE}-unit square on a\n` +
    `// ${UNIT}-unit pitch (the gap between cells is in the path); row 0 is the cap top.\n` +
    'export const wordmark = {\n' +
    `  width: ${cols * UNIT},\n` +
    `  height: ${rows * UNIT},\n` +
    `  capRows: ${capRows},\n` +
    `  path: '${parts.join('')}',\n` +
    '}\n',
)
console.log(`src/components/ui/wordmark-cells.ts: ${cells.length} cells, ${cols} x ${rows}, path ${parts.join('').length} characters`)
